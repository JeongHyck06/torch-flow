def test_shared_instance_is_built_once_and_called_twice():
    """가중치 공유는 코드에서도 공유로 남아야 한다(§7.2.5)."""
    ir = load(MINIVIT)
    scope = ir.composites["MLP"]
    # fc1을 두 번 부르는 그래프로 만든다.
    from torchflow.ir import Node

    scope.nodes.append(Node(label="fc1_again", id="dup", call="01J9I401", method="forward"))
    scope.edges = [edge for edge in scope.edges if edge != ["01J9Q4D3.output", "$out.y"]]
    scope.edges += [("01J9Q4D3.output", "dup.input"), ("dup.output", "$out.y")]

    body = codegen.generate(ir).split("class MLP(nn.Module):")[1].split("class ")[0]
    assert body.count("self.fc1 = nn.Linear") == 1
    assert body.count("self.fc1(") == 2


def test_graph_without_an_output_node_returns_its_sink():
    """Output 노드를 안 붙였어도 끝나는 데는 있다 - 아무도 소비하지 않는 값이 결과다."""
    ir = load(MINIVIT)
    ir.graph.nodes = [node for node in ir.graph.nodes if node.label != "logits"]
    ir.graph.edges = [edge for edge in ir.graph.edges if "01J9Q4B6" not in edge[1]]

    body = codegen.generate(ir).split("class MiniViT(nn.Module):")[1]
    assert "return head" in body


def test_train_block_stays_out_of_the_model():
    """학습 블록은 모델 코드에 나타나지 않는다. Output 뒤에 붙어 있어도 forward는 로짓을 돌려준다."""
    from torchflow.ir import ModuleGraph

    ir = ModuleGraph.model_validate({
        "graph": {"name": "tiny", "nodes": [
            {"id": "IN", "label": "x", "type": "torchflow.Input",
             "ports_out": [{"name": "x", "type": "Tensor", "shape": ["B", 8], "dtype": "float32"}]},
            {"id": "OUT", "label": "logits", "type": "torchflow.Output"},
            {"id": "TR", "label": "train", "type": "torchflow.Train",
             "args": {"optimizer": "sgd", "lr": 0.005, "steps": 7, "batch": 4}}],
            "edges": [["IN.x", "OUT.input"], ["OUT.output", "TR.input"]]}})
    code = codegen.generate(ir, version="0.0.1")
    ast.parse(code)
    assert "Train" not in code and "sgd" not in code
    assert "return x" in code
