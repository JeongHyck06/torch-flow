def test_generated_weights_are_bit_identical_to_the_kernel():
    """UI가 보여준 모델과 생성 코드가 같은 가중치에서 출발한다(§5.1.3, §10.4).

    이게 깨지면 "화면에서 본 grad"와 "스크립트가 내는 grad"가 다른 모델의 것이 된다.
    """
    torch = pytest.importorskip("torch")

    from torchflow.kernel.l1 import L1Pass, ProbeConfig

    ir = load(MINIVIT)
    model = module_of(codegen.generate(ir), "MiniViT")(num_classes=10, seed=0)
    generated_params = dict(model.named_parameters())

    pass_ = L1Pass(ir, rt={"num_classes": 10}, seed=0, probe=ProbeConfig(batch=2))
    pass_.probe_once()

    checked = 0
    for key, _node, _path in pass_.node_order:
        module_key = pass_.node_modules.get(key)
        module = pass_.session.modules.get(module_key) if module_key else None
        if module is None:
            continue
        prefix = pass_._label_path(key)
        for name, value in module.named_parameters():
            other = generated_params.get(f"{prefix}.{name}")
            assert other is not None, f"생성 코드에 없는 파라미터: {prefix}.{name}"
            assert torch.equal(other.detach(), value.detach()), f"{prefix}.{name} 값이 다르다"
            checked += 1
    assert checked > 50


