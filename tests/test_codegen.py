def test_user_slots_round_trip():
    ir = load(MINIVIT)
    ir.graph.user_code = {"forward_tail": "print('hi')", "imports_helpers": "import math"}
    code = codegen.generate(ir)

    assert "# tf: user-begin forward_tail\n        print('hi')\n        # tf: user-end" in code
    assert "# tf: user-begin imports_helpers\nimport math\n# tf: user-end" in code


def test_generated_model_runs_and_matches_the_declared_output():
    torch = pytest.importorskip("torch")
    model = module_of(generated(), "MiniViT")(num_classes=10, seed=0)

    output = model(torch.randn(2, 3, 32, 32))
