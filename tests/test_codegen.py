"""그래프 -> PyTorch 코드 (기획서 §7.2, §7.3, §10.4)."""

import ast

import pytest

from conftest import MINIVIT, ROOT
from torchflow import codegen
from torchflow.ir import load

RESNET = ROOT / "examples" / "resnet18.tfg.json"


def generated(path=MINIVIT) -> str:
    return codegen.generate(load(path), version="0.0.1")


def module_of(code: str, name: str):
    """생성된 소스를 실제로 실행해 클래스를 꺼낸다."""
    namespace: dict = {}
    exec(compile(code, "<generated>", "exec"), namespace)   # noqa: S102 - 생성 코드가 도는지가 요점
    return namespace[name]


def test_generated_code_parses_and_needs_only_torch():
    code = generated()

    ast.parse(code)
    assert "torchflow" not in code.replace("Generated by TorchFlow", "")
    imports = {line.split()[1] for line in code.splitlines()
               if line.startswith("import ") or line.startswith("from ")}
    assert imports <= {"__future__", "torch", "hashlib"}


def test_generation_is_deterministic():
    """같은 IR이면 바이트가 같다 - torchflow check의 전제다(§10.2)."""
    assert generated() == generated()


def test_composite_becomes_a_class_and_instance_an_attribute():
    code = generated()

    assert "class PatchEmbed(nn.Module):" in code
    assert "class MiniViT(nn.Module):" in code
    assert "self.proj = nn.Conv2d(in_channels=in_ch, out_channels=dim" in code
    # 컴포지트 doc은 클래스 docstring이 된다.
    assert '"""Conv patchifier followed by a flatten/transpose to token sequence."""' in code


def test_switch_branches_only_in_init():
    """forward는 변형을 모른다 - 런타임 isinstance 금지(§4.4.2 불변식)."""
    code = generated()
    block = code.split("class Block(nn.Module):")[1].split("class ")[0]
    init, forward = block.split("def forward")

    assert "if attn_type == 'baseline':" in init
    assert "SelfAttentionMHA" in init and "NoAttention" in init
    # forward에는 분기가 없고 호출 한 줄뿐이다.
    assert "self.attn(norm1)" in forward
    assert "if " not in forward


